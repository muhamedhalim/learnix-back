import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';

import { Type } from 'class-transformer';
import {
  ArrayMaxSize,
  IsArray,
  IsNotEmpty,
  IsNumber,
  IsOptional,
  IsString,
  IsUUID,
  MaxLength,
  Min,
  ValidateNested,
} from 'class-validator';

export class HomeworkQuestionDto {
  @ApiPropertyOptional({ description: 'Stable id; generated by the server when omitted' })
  @IsOptional()
  @IsUUID()
  public id?: string;

  @ApiProperty({ maxLength: 1000 })
  @IsString()
  @IsNotEmpty()
  @MaxLength(1000)
  public prompt!: string;

  @ApiPropertyOptional({ maxLength: 1000 })
  @IsOptional()
  @IsString()
  @MaxLength(1000)
  public prompt_ar?: string;
}

export class HomeworkAnswerDto {
  @ApiProperty()
  @IsUUID()
  public question_id!: string;

  @ApiProperty({ maxLength: 10_000 })
  @IsString()
  @MaxLength(10_000)
  public answer!: string;
}

export class SubmitHomeworkDto {
  @ApiPropertyOptional({ description: 'Free-form response', maxLength: 50_000 })
  @IsOptional()
  @IsString()
  @MaxLength(50_000)
  public answer_text?: string;

  @ApiPropertyOptional({ type: [HomeworkAnswerDto] })
  @IsOptional()
  @IsArray()
  @ArrayMaxSize(50)
  @ValidateNested({ each: true })
  @Type(() => HomeworkAnswerDto)
  public answers?: HomeworkAnswerDto[];

  @ApiPropertyOptional({ description: 'URL returned by /student/homework/:id/upload' })
  @IsOptional()
  @IsString()
  @MaxLength(1000)
  public resource_url?: string;

  @ApiPropertyOptional({ description: 'Original uploaded filename (display only)', maxLength: 255 })
  @IsOptional()
  @IsString()
  @MaxLength(255)
  public resource_filename?: string;
}

export class GradeHomeworkDto {
  @ApiProperty({ minimum: 0 })
  @IsNumber({ maxDecimalPlaces: 2 })
  @Min(0)
  public score!: number;

  @ApiPropertyOptional({ maxLength: 10_000 })
  @IsOptional()
  @IsString()
  @MaxLength(10_000)
  public feedback?: string;
}
